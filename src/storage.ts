// Storage layer for the DoStuff extension.
//
// With a workspace open: a single SQLite database at
// <workspace>/<settings.storagePath>/dostuff.db, accessed via sql.js (WASM).
// Attachment bytes still live on disk under <storagePath>/attachments/
// <issueId>/<attachmentId><ext>; the DB carries only Attachment metadata.
//
// With no workspace: ExtensionContext.globalState under STATE_KEY_FALLBACK
// (unchanged from the JSON era — no good filesystem path for a no-workspace
// DB without using globalStorageUri, which is out of scope here).
//
// One-shot migration: on first init with a workspace, any pre-existing
// `<id>.json` ticket files are read, normalised, inserted into the DB, then
// moved into `<storagePath>/legacy-json-backup/` as a recovery escape hatch.

