// Storage core for DoStuff — vscode-free by design.
//
// This is the single write path for ticket data: sql.js database (wholesale
// export via tmp+rename), `normalize()` migration chokepoint, the mutator/
// tombstone chokepoints for sync, and attachment byte IO. The VSCode
// extension wraps it in `storage.ts` (config resolution, globalState KV,
// workspace.fs-backed StorageFs); the headless CLI runs it directly on
// `node:fs`.
//
// With a storage directory: a single SQLite database at
// <storageDir>/dostuff.db, accessed via sql.js (WASM). Attachment bytes live
// on disk under <storageDir>/attachments/<issueId>/<attachmentId><ext>; the
// DB carries only Attachment metadata.
//
// With no storage directory: the host-provided KV fallback (the extension's
// `globalState`), unchanged from the JSON era. A host that provides no KV
// must always provide a storage directory.
//
// One-shot migration: on first init with a storage directory, any
// pre-existing `<id>.json` ticket files are read, normalised, inserted into
// the DB, then moved into `<storageDir>/legacy-json-backup/` as a recovery
// escape hatch.

