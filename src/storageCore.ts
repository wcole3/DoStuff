/**
 * Filesystem operations the store needs, as async string-path calls. The
 * default is `node:fs` (`nodeStorageFs`); the VSCode adapter maps these onto
 * `vscode.workspace.fs` so the extension keeps exactly its historical IO
 * semantics (and the storage test suite keeps its virtual-FS harness).
 */
/**
 * What a store mutation changed. `issues` is the whole (unsorted) cache for
 * consumers that want it; `upserted` / `removed` let subscribers forward a
 * delta instead of re-sending the board, and `reset: true` means the cache
 * was rebuilt wholesale (init, import, merge) so a full refresh is needed.
 */
export interface StoreChange {
  issues: Issue[];
  upserted: Issue[];
  removed: string[];
  reset: boolean;
}

export interface StorageFs {
  readFile(path: string): Promise<Uint8Array>;
  writeFile(path: string, content: Uint8Array): Promise<void>;
  /** Recursive, idempotent mkdir. */
  createDirectory(path: string): Promise<void>;
  /** Missing targets must not throw. */
  delete(path: string, opts?: { recursive?: boolean }): Promise<void>;
  exists(path: string): Promise<boolean>;
  readDirectory(path: string): Promise<Array<[string, "file" | "directory" | "other"]>>;
  /** Must overwrite an existing target (POSIX rename semantics). */
  rename(from: string, to: string): Promise<void>;
}

export const nodeStorageFs: StorageFs = {
  readFile: (p) => fs.promises.readFile(p),
  writeFile: (p, content) => fs.promises.writeFile(p, content),
  createDirectory: async (p) => {
    await fs.promises.mkdir(p, { recursive: true });
  },
  delete: async (p, opts) => {
    await fs.promises.rm(p, { recursive: opts?.recursive ?? false, force: true });
  },
  exists: async (p) => {
    try {
      await fs.promises.stat(p);
      return true;
    } catch {
      return false;
    }
  },
  readDirectory: async (p) => {
    const entries = await fs.promises.readdir(p, { withFileTypes: true });
    return entries.map((d) => [
      d.name,
      d.isFile() ? "file" : d.isDirectory() ? "directory" : "other",
    ]);
  },
  rename: (from, to) => fs.promises.rename(from, to),
};

